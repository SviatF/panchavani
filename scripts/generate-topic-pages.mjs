/** Static ONLY: generate city/topic paths from reviewed scientific + editorial
 * bundle and a second independent SEO allowlist. Zero approved = zero routes.
 * No DeepSeek invocation or private R2 research access in the public build.
 */
import {readFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {validateTopicContent,validateTopicSeo} from '../lib/topic-release-policy.mjs';

const root=process.cwd(),dataDir=path.join(root,'data');
const pageManifest=JSON.parse(await readFile(path.join(dataDir,'approved-topic-pages.json'),'utf8'));
const seoManifest=JSON.parse(await readFile(path.join(dataDir,'approved-topic-seo.json'),'utf8'));
const scienceBundle=JSON.parse(await readFile(path.join(dataDir,'approved-panchang.json'),'utf8'));
const digest=x=>createHash('sha256').update(JSON.stringify(x)).digest('hex');
const sha=x=>typeof x==='string'&&/^[a-f0-9]{64}$/.test(x);
if(scienceBundle.records.length){
 const expected=process.env.PANCHAVANI_APPROVED_RELEASE_SHA256;
 if(!sha(expected)||digest(scienceBundle)!==expected||
    scienceBundle.releaseStatus!=='HUMAN_REVIEWED_WITH_EVIDENCE')
  throw Error('Topic pages cannot be generated from unauthenticated science bundle');
}
const articles=validateTopicContent(pageManifest,scienceBundle.records,
 process.env.PANCHAVANI_APPROVED_TOPIC_RELEASE_SHA256);
const routes=validateTopicSeo(seoManifest,articles,
 process.env.PANCHAVANI_APPROVED_TOPIC_SEO_SHA256);
const keys=routes.map(x=>x.path.slice(1,-1)),set=new Set(keys);
if(set.size!==keys.length)throw Error('Duplicate published topic route');
const paths=path.join(root,'app','.generated-reviewed-topic-paths.json');
const safeKey=x=>typeof x==='string'&&/^[a-z0-9][a-z0-9/-]*$/.test(x)&&
 !x.includes('//')&&!x.includes('..')&&
 /^(calendar|festivals|vrat|muhurat)\//.test(x)&&
 x.split('/').length>=4&&x.split('/').every(p=>p.length>0);
for(const key of keys)if(!safeKey(key))throw Error('Unsafe topic static route key');
let old=[];
try{old=JSON.parse(await readFile(paths,'utf8'))}
catch(error){if(error?.code!=='ENOENT')throw error}
if(!Array.isArray(old)||!old.every(safeKey))throw Error('Unsafe old topic path manifest');
for(const key of old){
 if(!set.has(key))await rm(path.join(root,'app',key,'page.tsx'),{force:true});
}
for(const key of set){
 const target=path.join(root,'app',key,'page.tsx');
 const sitePath='/'+key+'/';
 const code=`// Generated by scripts/generate-topic-pages.mjs; do not edit.\n`+
  `import {ReviewedTopicPage,reviewedTopicMetadata} from '@/components/reviewed-topic-page';\n`+
  `export const metadata=reviewedTopicMetadata(${JSON.stringify(sitePath)});\n`+
  `export default function Page(){return <ReviewedTopicPage path=${JSON.stringify(sitePath)}/>;}\n`;
 await mkdir(path.dirname(target),{recursive:true});
 await writeFile(target,code,'utf8');
}
await writeFile(paths,JSON.stringify([...set].sort())+'\n','utf8');
console.log('PANCHAVANI fully reviewed and SEO-approved city-topic URLs:',set.size);
