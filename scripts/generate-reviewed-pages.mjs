/** Prebuild only: physical static date routes for independently reviewed records.
 * Next.js 15 static export rejects a dynamic route whose static params are [];
 * NEVER create demo URLs or mock values just to satisfy the exporter.
 */
import {readFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {assessFirstRelease} from './approved-day-value-gate.mjs';
import {validateSeoDayRelease} from '../lib/seo-day-release-policy.mjs';

const root=process.cwd();
const file=path.join(root,'data','approved-panchang.json');
const manifest=path.join(root,'app','panchang','.generated-reviewed-day-paths.json');
const seoManifest=path.join(root,'data','approved-seo-days.json');
const validDay=value=>typeof value==='string'&&/^20\d{2}-\d{2}-\d{2}$/.test(value)&&
 !Number.isNaN(Date.parse(value+'T12:00:00Z'))&&
 new Date(value+'T12:00:00Z').toISOString().slice(0,10)===value;
const VALID_CITIES=new Set(['delhi','mumbai','kolkata','chennai','bengaluru','hyderabad','ahmedabad','pune','jaipur','varanasi']);
const safePair=(city,date)=>VALID_CITIES.has(city)&&validDay(date);
const abs=(city,date)=>path.join(root,'app','panchang',city,date,'page.tsx');
const payload=JSON.parse(await readFile(file,'utf8'));
if(payload?.schemaVersion!==1||!Array.isArray(payload.records))
 throw Error('Approved manifest has invalid schema');
const digest=process.env.PANCHAVANI_APPROVED_RELEASE_SHA256;
if(payload.records.length&&(!/^[a-f0-9]{64}$/.test(digest||'')||
 createHash('sha256').update(JSON.stringify(payload)).digest('hex')!==digest))
 throw Error('Approved records require exact independently reviewed build-time SHA-256');
if(payload.records.length&&payload.releaseStatus!=='HUMAN_REVIEWED_WITH_EVIDENCE')
 throw Error('Approved records must have reviewed release status');
// A signed SHA is a provenance lock, never proof of valuable or correct content.
if(payload.records.length){
 const quality=assessFirstRelease(payload.records);
 if(!quality.readyForHumanReleaseReview)
  throw Error('City/day evidence and uniqueness gate failed: '+
   JSON.stringify(quality.rows.filter(x=>x.issues.length)));
}
// The daily SEO allowlist is separately approved, not inferred from data.
const seo=JSON.parse(await readFile(seoManifest,'utf8'));
const indexable=validateSeoDayRelease(
 seo,payload.records,process.env.PANCHAVANI_APPROVED_SEO_RELEASE_SHA256
);
console.log('PANCHAVANI independently approved SEO day URLs:',indexable.length);
const next=new Set();
for(const record of payload.records){
 if(!safePair(record?.cityId,record?.date)||record?.status!=='approved')
  throw Error('Approved manifest contains invalid or unapproved city/day identity');
 const key=record.cityId+'/'+record.date;
 if(next.has(key))throw Error('Duplicate reviewed city/day route');
 next.add(key);
}
let previous=[];
try{
 const saved=JSON.parse(await readFile(manifest,'utf8'));
 if(!Array.isArray(saved))throw Error('Invalid prior generated route registry');
 previous=saved;
}catch(error){
 if(error?.code!=='ENOENT')throw error;
}
for(const key of previous){
 const [city,date,...extra]=typeof key==='string'?key.split('/'):[];
 if(!safePair(city,date)||extra.length)throw Error('Unsafe generated route registry entry');
 if(!next.has(key))await rm(abs(city,date),{force:true});
}
for(const key of next){
 const [city,date]=key.split('/');
 const target=abs(city,date);
 const code=`// Generated by scripts/generate-reviewed-pages.mjs. DO NOT edit.\n`+
  `import {ReviewedDayPage,reviewedDayMetadata} from '@/components/reviewed-day-page';\n`+
  `export const metadata=reviewedDayMetadata(${JSON.stringify(city)},${JSON.stringify(date)});\n`+
  `export default function Page(){return <ReviewedDayPage city=${JSON.stringify(city)} date=${JSON.stringify(date)}/>;}\n`;
 await mkdir(path.dirname(target),{recursive:true});
 await writeFile(target,code,'utf8');
}
await writeFile(manifest,JSON.stringify([...next].sort())+'\n','utf8');
console.log('PANCHAVANI reviewed date pages:',next.size,'(0 mock pages, 0 DeepSeek calls)');
